def plot_annualized_return(engine):
    query = "SELECT Date, NetProfit FROM net_profit_daily_record"
    with engine.connect() as connection: df = pd.DataFrame(connection.execute(text(query)).fetchall(), columns=['Date', 'NetProfit'])

    # Calculate Bot Running Time
    with engine.connect() as connection: df_earliest = pd.DataFrame(connection.execute(text('SELECT MIN(time_create) FROM position_table')).fetchall(), columns=['time_create'])
    earliest_transactTime = df_earliest['time_create'].iloc[0]
    duration = (int(time.time() * 1000) - earliest_transactTime) / 1000 / 60 / 60
    duration_day = f'{int(duration / 24)} D {int(duration % 24)} H' if duration > 24 else f'{int(duration)} Hours'

    # Calculate Annualized APY
    with engine.connect() as connection: df_profit = pd.DataFrame(connection.execute(text('SELECT SUM(profit) FROM position_table WHERE is_closed = 1 AND account = "spot"')).fetchall(), columns=['profit'])
    profit_sum = df_profit['profit'].iloc[0]
    profit_sum = float(profit_sum)
    roi = profit_sum / INITIAL_FUND
    annualized_return = profit_sum / (duration / 24 / 365) / INITIAL_FUND
    annualized_return_percent = f"{annualized_return * 100:.2f}%"

    # Calculate Return as a Percentage
    df['ReturnPercent'] = (df['NetProfit'] / INITIAL_FUND) * 100

    metric_col1, metric_col2, metric_col3 = st.columns(3)
    metric_col1.metric("DUATION", duration_day, datetime.utcfromtimestamp(earliest_transactTime/1000).strftime('%Y-%m-%d'))
    metric_col2.metric("ROI", f"{format_number(roi*100)}%", format_number(profit_sum))
    metric_col3.metric("APY", annualized_return_percent, format_number(annualized_return))
    
    fig, ax1 = plt.subplots(figsize=(12, 8))

    ax1.plot(df['Date'], df['NetProfit'], color='green')
    ax1.set_ylabel('Net Profit', color='black')

    # Create a secondary y-axis for the percentage return
    ax2 = ax1.twinx()
    ax2.plot(df['Date'], df['ReturnPercent'], color='green')
    ax2.set_ylabel('Return (%)', color='black')

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("<h1 style='text-align: center;'>Annualized Return Chart</h1>", unsafe_allow_html=True)
        plt.title('Daily Return')
        st.pyplot(fig)

    with col2:
        st.markdown("<h1 style='text-align: center;'>Performance by Coin</h1>", unsafe_allow_html=True)
        plt.title('Performance by coin')
        plot_performance_by_coin(engine)

    return

def plot_performance_by_coin(engine):
    # Query to calculate the total profit generated by each symbol
    sell_query = "SELECT symbol, SUM(profit) as total_profit FROM position_table GROUP BY symbol"
    sell_count_query = "SELECT symbol, COUNT(*) as trade_count FROM position_table GROUP BY symbol"
    
    with engine.connect() as connection: result = connection.execute(text(sell_query)).fetchall()
    df_sell = pd.DataFrame(result, columns=['symbol', 'total_profit'])
    
    with engine.connect() as connection: count_result = connection.execute(text(sell_count_query)).fetchall()
    df_count = pd.DataFrame(count_result, columns=['symbol', 'trade_count'])

    # Merge the two dataframes on symbol
    df_merged = pd.merge(df_sell, df_count, on='symbol')
    
    # Add a new column 'coin' by slicing the 'symbol' column
    df_merged['coin'] = df_merged['symbol'].str[:-4]

    df_merged['total_profit'] = pd.to_numeric(df_merged['total_profit'], errors='coerce')

    # Filter to top 10 positive and top 5 negative profit coins
    top_positive = df_merged[df_merged['total_profit'] > 0].nlargest(5, 'total_profit')
    top_negative = df_merged[df_merged['total_profit'] < 0].nsmallest(5, 'total_profit')
    df_filtered = pd.concat([top_positive, top_negative]).sort_values(by='total_profit', ascending=False)

    colors = ['red' if x < 0 else 'green' for x in df_filtered['total_profit']]
    
    # Plotting the total profit
    fig, ax1 = plt.subplots(figsize=(12, 8))
    ax1.bar(df_filtered['coin'], df_filtered['total_profit'], color=colors)
    ax1.set_ylabel('Total Profit', color='black')
    ax1.tick_params(axis='y', labelcolor='black')

    # Create a secondary y-axis for trade count
    ax2 = ax1.twinx()
    ax2.plot(df_filtered['coin'], df_filtered['trade_count'], color='grey', marker='o', linestyle='-')
    ax2.set_ylabel('Trade Count', color='black')
    ax2.tick_params(axis='y', labelcolor='black')

    # Add labels and title
    plt.xticks(rotation=45)
    # ax1.set_xlabel('Coins')
    plt.title('Top Performing and Worst Performing Coins')

    st.pyplot(fig)
    return 


def display_binance_position_sell(engine):
    try:
        with engine.connect() as connection: df_merged = pd.DataFrame(connection.execute(text('SELECT * FROM position_table WHERE is_closed = 1 ORDER BY time_create DESC')).fetchall())
    except: df_merged = pd.DataFrame()
    if df_merged.empty: return
    df_merged['duration_min'] = df_merged['duration'].apply(lambda x: int(x/1000/60))
    df_merged['time_create'] = df_merged['time_create'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%Y-%m-%d %H:%M'))
    df_merged['time_close'] = df_merged['time_close'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%Y-%m-%d %H:%M'))
    df_merged = df_merged[['coin', 'profit', 'account', 'type_create', 'type_close', 'duration_min', 'time_create', 'time_close', 'price_create', 'price_close', 'orderId_create', 'orderId_close']]
    df_merged.sort_values(by=['profit'], ascending=False, inplace=True)
    csv = df_merged.to_csv(index=False)
    b64 = base64.b64encode(csv.encode()).decode()
    href = f'<a href="data:file/csv;base64,{b64}" download="binance_position_table.csv">Download CSV File</a>'
    st.markdown(href, unsafe_allow_html=True)
    with st.expander("Position BUY & SELL History", expanded=False):  st.table(df_merged)
    return


def display_open_position(engine):
    try:
        with engine.connect() as connection: df_buy = pd.DataFrame(connection.execute(text('SELECT coin, account, orderId_create, time_create, price_create, orderId_close FROM position_table WHERE is_closed = 0 ORDER BY time_create DESC')).fetchall())
    except: df_buy = pd.DataFrame()
    if df_buy.empty: return
    df_buy['duration'] = int(time.time() * 1000) - df_buy['time_create']
    df_buy['duration_hour'] = df_buy['duration'].apply(lambda x: int(x/1000/60/60))
    df_buy['time_create'] = df_buy['time_create'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%Y-%m-%d %H:%M'))
    # drop 'duration' column
    df_buy.drop(['duration'], axis=1, inplace=True)
    with st.expander("Open Positions", expanded=False): 
        if df_buy.empty: st.write("No open positions currently.")
        else: st.table(df_buy)
    return 


def display_funding_account_performance(engine):
    try: 
        with engine.connect() as connection: df = pd.DataFrame(connection.execute(text(f'SELECT coin, profit, price_create, price_close, orderId_create, orderId_close, time_create, time_close, duration FROM position_table WHERE account = "funding" AND is_closed = 1')).fetchall())
    except: pd.DataFrame()

    with st.expander("Funding Account Performance", expanded=False): 
        if df.empty: st.write("No funding account performance data.")
        else:
            df['time_create'] = df['time_create'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%Y-%m-%d %H:%M'))
            df['time_close'] = df['time_close'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%Y-%m-%d %H:%M'))
            df['duration_hour'] = df['duration'].apply(lambda x: int(x/1000/60/60))
            total_profit = df['profit'].sum()
            st.write(f"Total Profit: {format_number(total_profit)}")
            st.table(df)


def display_daily_profit_take(engine):
    try: 
        with engine.connect() as connection: df_today = pd.DataFrame(connection.execute(text('SELECT * FROM daily_profit_take')).fetchall()) 
    except: df_today = pd.DataFrame()
    with st.expander("Daily Profit Take Record", expanded=False): 
        if df_today.empty: st.write("No daily profit take record.")
        else: 
            total_profit_take_of_this_year = df_today[df_today['date'].apply(lambda x: x.split('-')[0] == str(datetime.now().year))]['profit'].sum()
            today_month = datetime.now().month
            today_month = f'0{today_month}' if today_month < 10 else today_month
            total_profit_take_of_this_month = df_today[df_today['date'].apply(lambda x: x.split('-')[1] == str(today_month))]['profit'].sum()
            st.write(f"Total Profit Take of This Year: {format_number(total_profit_take_of_this_year)} | Total Profit Take of This Month: {format_number(total_profit_take_of_this_month)}")
            df_today['profit'] = df_today['profit'].apply(lambda x: int(x))
            df_today['update_timestamp'] = df_today['update_timestamp'].apply(lambda x: datetime.fromtimestamp(x/1000).strftime('%H:%M'))
            st.table(df_today)


