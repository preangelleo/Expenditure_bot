    df_whitelist = pd.DataFrame(engine.connect().execute(whitelist_query).fetchall(), columns=['symbol'])
    df_ignorelist = pd.DataFrame(engine.connect().execute(ignorelist_query).fetchall(), columns=['symbol'])
    col1, col2 = st.columns(2)
    with col1:
        with st.expander("Whitelist", expanded=False): st.table(df_whitelist)

    with col2:
        with st.expander("Ignore List", expanded=False): st.table(df_ignorelist)

